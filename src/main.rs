use compiler::{Compiler, LolCompiler};
use std::path::Path;
use std::process;

// Shows an error if the user runs the program incorrectly.
fn usage_error(message: &str) -> ! {
    eprintln!("Usage error: {}", message);
    eprintln!("Usage: lolcompiler <input.lol>");
    process::exit(1);
}

// Opens the HTML file in the default browser.
fn open_in_browser(path: &Path) {
    #[cfg(target_os = "windows")]
    let result = process::Command::new("cmd")
        .args(["/C", "start", ""])
        .arg(path)
        .spawn();

    #[cfg(target_os = "macos")]
    let result = process::Command::new("open").arg(path).spawn();

    #[cfg(not(any(target_os = "windows", target_os = "macos")))]
    let result = process::Command::new("xdg-open").arg(path).spawn();

    // Shows a warning if the browser could not open.
    if let Err(e) = result {
        eprintln!("Warning: could not open browser: {}", e);
    }
}

fn main() {
    // Gets the arguments entered by the user.
    let args: Vec<String> = std::env::args().collect();

    // The program must receive exactly one input file.
    if args.len() != 2 {
        usage_error("expected exactly one input file");
    }

    // Checks that the input file has the .lol extension.
    let input = Path::new(&args[1]);
    let is_lol = input
        .extension()
        .map(|ext| ext.eq_ignore_ascii_case("lol"))
        .unwrap_or(false);

    if !is_lol {
        usage_error(&format!(
            "'{}' does not have a .lol extension",
            args[1]
        ));
    }

    // Reads the LOLCODE file.
    let source = std::fs::read_to_string(input).unwrap_or_else(|e| {
        usage_error(&format!("could not read '{}': {}", args[1], e));
    });

    // Creates the compiler and compiles the source code.
    let mut compiler = LolCompiler::new();
    compiler.compile(&source);

    // Gets the HTML generated by the compiler.
    let html = compiler.html.expect("compile succeeded");

    // Saves the HTML in the same folder with the same name.
    let output = input.with_extension("html");

    if let Err(e) = std::fs::write(&output, html) {
        eprintln!("Error: could not write '{}': {}", output.display(), e);
        process::exit(1);
    }

    println!("Compiled successfully: {}", output.display());

    // Gets the full path so the browser can open the file.
    let absolute = std::fs::canonicalize(&output).unwrap_or(output);
    open_in_browser(&absolute);
}